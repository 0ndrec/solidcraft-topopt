#!/usr/bin/env bash
# Build the GPU kernels of topopt-cuda (crates/topopt-cuda/kernels: Rust for nvptx64-nvidia-cuda)
# into crates/topopt-cuda/src/kernels.ptx, which is checked in: building and running the solver
# needs neither this toolchain nor a CUDA toolkit, only the NVIDIA driver to run on a GPU.
#
#   rustup toolchain install nightly --profile minimal --component llvm-tools,llvm-bitcode-linker,rust-src --target nvptx64-nvidia-cuda
#   scripts/build-ptx.sh                      # PTX_TOOLCHAIN=nightly-x86_64-pc-windows-gnu to pick one
#
# Rust's nvptx target emits PTX for sm_70 (Volta) and later. The kernels use no instruction newer
# than sm_32, so the PTX is retargeted to sm_52: Maxwell and Pascal GPUs can then load it too (the
# driver checks every instruction when it compiles the PTX for the GPU at hand).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
toolchain="${PTX_TOOLCHAIN:-nightly}"
kernels="$root/crates/topopt-cuda/kernels"
out="$root/crates/topopt-cuda/src/kernels.ptx"
cargo "+$toolchain" build --release --target nvptx64-nvidia-cuda --manifest-path "$kernels/Cargo.toml" --target-dir "$root/target/ptx"
ptx="$root/target/ptx/nvptx64-nvidia-cuda/release/topopt_cuda_kernels.ptx"
grep -q '^\.target sm_70$' "$ptx" || { echo "build-ptx: expected .target sm_70 in $ptx" >&2; exit 1; }
# FNV-1a 64 of the kernel source (line endings normalized), checked by topopt-cuda's tests.
hash="$(python - "$kernels/lib.rs" <<'EOF'
import sys
h = 0xCBF29CE484222325
for b in open(sys.argv[1], "rb").read().replace(b"\r\n", b"\n"):
    h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
print(f"{h:016x}")
EOF
)"
{
    echo "// Generated by scripts/build-ptx.sh from kernels/lib.rs ($(rustc "+$toolchain" --version)); do not edit."
    echo "// source fnv1a64: $hash"
    sed -e 's/^\.target sm_70$/.target sm_52/' "$ptx" | tr -d '\r'
} > "$out"
echo "$out: $(wc -c < "$out") bytes, $(grep -c '^\.visible \.entry' "$out") kernels"
